test("an existing stable ledger is not replaced, and a held legacy owner blocks adoption", async () => {
	const root = await realpath(await mkdtemp(join(tmpdir(), "datastore-stable-ledger-")));
	await prepareQmdStateDirectory(root);
	const config = { stateRoot: root, stores: new Map([["notes", { name: "notes" }]]) } as any;
	const legacyDir = qmdApplicationDirectory(config, "2.8.3");
	const legacy = new MaintenanceCoordinator(join(legacyDir, "jobs.json"), () => new Set(["notes"]));
	legacy.register("metadata", async () => ({ generation: "meta-" + "ab".repeat(16) }));
	await legacy.enqueue("metadata", ["notes"], "explicit-maintenance");
	await legacy.settled();
	legacy.shutdown();
	const stable = join(root, "jobs.json");
	await writeFile(stable, JSON.stringify({ version: 1, jobs: [] }), { mode: 0o600 });
	const empty = await readFile(stable);
	await adoptLegacyApplicationJobs(root, stable, new Set(["notes"]), (version) => qmdApplicationDirectory(config, version));
	assert.deepEqual(await readFile(stable), empty);
	await writeFile(stable, "{", { mode: 0o600 });
	const invalid = await readFile(stable);
	await adoptLegacyApplicationJobs(root, stable, new Set(["notes"]), (version) => qmdApplicationDirectory(config, version));
	assert.deepEqual(await readFile(stable), invalid);
	const rejected = new MaintenanceCoordinator(stable, () => new Set(["notes"]));
	await assert.rejects(rejected.ensureLoaded(), { code: "INDEX_CORRUPT" });
	rejected.shutdown();
	await rm(stable);
	const held = await acquireIndexOwnership(legacyDir);
	await assert.rejects(adoptLegacyApplicationJobs(root, stable, new Set(["notes"]), (version) => qmdApplicationDirectory(config, version)), { code: "STORE_UNAVAILABLE" });
	await assert.rejects((await import("node:fs/promises")).lstat(stable), { code: "ENOENT" });
	await held.release();
	await rm(root, { recursive: true, force: true });
});

