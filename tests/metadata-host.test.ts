import assert from "node:assert/strict";
import { chmod, mkdir, mkdtemp, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { loadMarkdownDatastoreConfig } from "../src/config.ts";
import { MaintenanceCoordinator } from "../src/maintenance-coordinator.ts";
import { MetadataIndex, registerMetadata } from "../src/metadata-index.ts";
import { MarkdownDatastoreService } from "../src/service.ts";

test("one coordinator serves graph-only refresh, links, tags, and cancel", async (t) => {
	const project = await realpath(await mkdtemp(join(tmpdir(), "datastore-host-")));
	t.after(() => rm(project, { recursive: true, force: true }));
	const notes = join(project, "notes");
	const dir = join(project, ".pi", "markdown-datastore");
	await mkdir(notes, { recursive: true });
	await mkdir(dir, { recursive: true, mode: 0o700 });
	await chmod(dir, 0o700);
	await writeFile(join(notes, "alpha.md"), "---\ntags: [Travel]\n---\nSee [[beta]] and ![[map.png]].\n");
	await writeFile(join(notes, "beta.md"), "Target.\n");
	await writeFile(join(notes, "map.png"), "png");
	const configPath = join(dir, "config.json");
	await writeFile(configPath, JSON.stringify({ schemaVersion: 1, defaults: { maxResultBytes: 8192, maxResultLines: 100, operationTimeoutMs: 3000 }, qmd: { enabled: false, installation: { executable: "qmd" }, minimumVersion: "2.8.3" }, stores: { memory: { root: "notes", include: ["**/*.md"], exclude: [], maxFileBytes: 4096, search: { defaultMode: "lexical", qmdCollection: "memory" } } } }), { mode: 0o600 });
	const config = await loadMarkdownDatastoreConfig(project, configPath);
	const coordinator = new MaintenanceCoordinator(join(dir, "state", "jobs.json"), () => new Set(config.stores.keys()));
	const indexes = new Map([["memory", new MetadataIndex(join(dir, "state"))]]);
	registerMetadata(coordinator, indexes, config.stores);
	const service = new MarkdownDatastoreService(config);
	service.bindMetadata(coordinator, indexes);
	t.after(() => service.shutdown());
	const started = await service.refresh({ action: "start", store: "memory", mode: "metadata" });
	assert.equal(started.data.qmd.coalesced, false);
	await coordinator.settled();
	const links = await service.read({ store: "memory", note: { store: "memory", path: "alpha.md" }, view: "links" });
	assert.equal(links.data.edges.length, 2);
	const back = await service.read({ store: "memory", note: { store: "memory", path: "map.png" }, view: "backlinks" });
	assert.equal(back.data.occurrenceCount, 1);
	const found = await service.find({ store: "memory", selectors: [{ kind: "tag", value: "#travel" }] });
	assert.equal(found.data.candidates[0].note.path, "alpha.md");
	const tags = await service.tags({ store: "memory" });
	assert.equal(tags.data.tags[0].identity, "travel");
	const held = new MaintenanceCoordinator(join(dir, "state", "other-jobs.json"), () => new Set(["memory"]));
	let release!: () => void;
	const gate = new Promise<void>((resolve) => { release = resolve; });
	held.register("metadata", async () => { await gate; return { generation: "meta-held" }; });
	const job = await held.enqueue("metadata", ["memory"], "explicit-maintenance");
	const detached = await held.cancel(String(job.refreshId));
	assert.equal(detached.cancellationRequested, true);
	release();
	await held.settled();
	await held.shutdown();
});
