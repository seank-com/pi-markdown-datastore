import assert from "node:assert/strict";
import { chmod, mkdir, mkdtemp, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { loadMarkdownDatastoreConfig } from "../src/config.ts";
import { MaintenanceCoordinator } from "../src/maintenance-coordinator.ts";
import { MetadataIndex } from "../src/metadata-index.ts";

test("metadata refresh uses the shared coordinator with qmd disabled", async (t) => {
	const project = await realpath(await mkdtemp(join(tmpdir(), "datastore-meta-")));
	t.after(() => rm(project, { recursive: true, force: true }));
	const notes = join(project, "notes");
	const dir = join(project, ".pi", "markdown-datastore");
	await mkdir(dir, { recursive: true, mode: 0o700 });
	await chmod(dir, 0o700);
	await mkdir(notes);
	await writeFile(join(notes, "alpha.md"), "---\ntags: [Travel]\n---\nSee [[beta]].\n");
	await writeFile(join(notes, "beta.md"), "Target.\n");
	const configPath = join(dir, "config.json");
	await writeFile(configPath, JSON.stringify({ schemaVersion: 1, defaults: { maxResultBytes: 8192, maxResultLines: 100, operationTimeoutMs: 3000 }, qmd: { enabled: false, installation: { executable: "qmd" }, minimumVersion: "2.8.3" }, stores: { memory: { root: "notes", include: ["**/*.md"], exclude: ["secret/**"], maxFileBytes: 4096, search: { defaultMode: "lexical", qmdCollection: "memory" } } } }), { mode: 0o600 });
	const config = await loadMarkdownDatastoreConfig(project, configPath);
	assert.equal(config.qmd.enabled, false);
	const store = config.stores.get("memory")!;
	const index = new MetadataIndex(join(dir, "state"));
	const coordinator = new MaintenanceCoordinator(join(dir, "state", "jobs.json"), () => new Set(config.stores.keys()));
	coordinator.register("metadata", async (_job, signal) => { const snapshot = await index.refresh(store, signal); return { generation: snapshot.revision }; });
	const first = await coordinator.enqueue("metadata", [store.name], "explicit-maintenance");
	const second = await coordinator.enqueue("metadata", [store.name], "explicit-maintenance");
	assert.equal(second.refreshId, first.refreshId);
	assert.equal(second.coalesced, true);
	await coordinator.settled();
	const snapshot = await index.snapshot();
	assert.equal(snapshot?.complete, true);
	assert.deepEqual(snapshot?.tags.travel, ["alpha.md"]);
	assert.equal(snapshot?.files["alpha.md"].links?.[0].target, "beta");
	assert.equal((await index.catalog())[0].spelling, "Travel");
	const edges = await index.links("alpha.md");
	assert.equal(edges[0].targetKind, "note");
	assert.equal(edges[0].target, "beta.md");
	await coordinator.shutdown();
	await index.shutdown();
});
